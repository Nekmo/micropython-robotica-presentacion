"""MicroPython raster backend: framebuf RGB565 + baked bitmap fonts.

Twin of raster_pil.py for the real-MicroPython runtime. Text uses the
1-bpp fonts generated by tools/bake_fonts.py (format "EMF1"); frames are
raw RGB565 compressed with deflate ("rgb565z", decoded by the GUI).
Colors arrive as 0xRRGGBB ints.
"""

import array
import framebuf
import math
import struct

from stackchan_sim import compat

_FONT_DIR = compat.path_join(compat.path_dirname(__file__), "fonts")
_FONT_SIZES = (8, 9, 10, 12, 14, 16, 18, 20, 22, 24, 28, 30, 36, 40, 44,
               48, 56, 72)
_fonts = {}


def _c565(color):
    color = int(color) & 0xFFFFFF
    r = (color >> 16) & 0xFF
    g = (color >> 8) & 0xFF
    b = color & 0xFF
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


class _Font:
    """Parsed EMF1 bitmap font."""

    def __init__(self, data):
        magic, self.height, self.ascent, self.first, self.count = \
            struct.unpack_from("<4sBBHH", data, 0)
        if magic != b"EMF1":
            raise ValueError("bad font file")
        pos = 10
        self.widths = data[pos:pos + self.count]
        pos += self.count
        self.offsets = struct.unpack_from("<%dI" % self.count, data, pos)
        pos += 4 * self.count
        self.bitmap = memoryview(data)[pos:]

    def glyph(self, code):
        i = code - self.first
        if i < 0 or i >= self.count:
            i = ord("?") - self.first
        return self.widths[i], self.offsets[i]


def _load_font(px):
    """Baked font nearest to the requested pixel size (cached)."""
    px = max(6, int(px))
    best = _FONT_SIZES[0]
    for size in _FONT_SIZES:
        if abs(size - px) < abs(best - px):
            best = size
    font = _fonts.get(best)
    if font is None:
        path = compat.path_join(_FONT_DIR, "dejavu_%d.bin" % best)
        with open(path, "rb") as fh:
            font = _Font(fh.read())
        _fonts[best] = font
    return font


class FbRaster:
    """Drawing surface backed by a framebuf RGB565 buffer."""

    def __init__(self, width, height):
        self.w = width
        self.h = height
        self._buf = bytearray(width * height * 2)
        self._fb = framebuf.FrameBuffer(self._buf, width, height,
                                        framebuf.RGB565)

    def make(self, width, height):
        return FbRaster(width, height)

    # ── primitives ───────────────────────────────────────────────────────
    def fill(self, c):
        self._fb.fill(_c565(c))

    def pixel(self, x, y, c):
        self._fb.pixel(int(x), int(y), _c565(c))

    def line(self, x0, y0, x1, y1, c):
        self._fb.line(int(x0), int(y0), int(x1), int(y1), _c565(c))

    def rect(self, x, y, w, h, c, fill=False):
        self._fb.rect(int(x), int(y), int(w), int(h), _c565(c), bool(fill))

    def round_rect(self, x, y, w, h, r, c, fill=False):
        if w <= 0 or h <= 0:
            return
        x, y, w, h = int(x), int(y), int(w), int(h)
        r = max(0, min(int(r), (min(w, h) - 1) // 2))
        col = _c565(c)
        if r == 0:
            self._fb.rect(x, y, w, h, col, bool(fill))
            return
        # corner centres
        lx, rx = x + r, x + w - 1 - r
        ty, by = y + r, y + h - 1 - r
        if fill:
            self._fb.rect(x, ty, w, h - 2 * r, col, True)
            self._fb.rect(lx, y, w - 2 * r, r, col, True)
            self._fb.rect(lx, by + 1, w - 2 * r, r, col, True)
        else:
            self._fb.hline(lx, y, w - 2 * r, col)
            self._fb.hline(lx, y + h - 1, w - 2 * r, col)
            self._fb.vline(x, ty, h - 2 * r, col)
            self._fb.vline(x + w - 1, ty, h - 2 * r, col)
        # quadrant masks: 1=TR 2=TL 4=BL 8=BR
        f = bool(fill)
        self._fb.ellipse(rx, ty, r, r, col, f, 1)
        self._fb.ellipse(lx, ty, r, r, col, f, 2)
        self._fb.ellipse(lx, by, r, r, col, f, 4)
        self._fb.ellipse(rx, by, r, r, col, f, 8)

    def ellipse(self, cx, cy, rx, ry, c, fill=False):
        self._fb.ellipse(int(cx), int(cy), int(rx), int(ry), _c565(c),
                         bool(fill))

    def triangle(self, x0, y0, x1, y1, x2, y2, c, fill=False):
        coords = array.array("h", (int(x0), int(y0), int(x1), int(y1),
                                   int(x2), int(y2)))
        self._fb.poly(0, 0, coords, _c565(c), bool(fill))

    def arc(self, cx, cy, r0, r1, angle0, angle1, c):
        """Radial-segment arc between radii r0..r1 (degrees)."""
        col = _c565(c)
        a0, a1 = float(angle0), float(angle1)
        if a1 < a0:
            a0, a1 = a1, a0
        span = min(360.0, a1 - a0)
        steps = max(2, int(span))  # ~1 degree per segment
        for i in range(steps + 1):
            ang = math.radians(a0 + span * i / steps)
            ca, sa = math.cos(ang), math.sin(ang)
            self._fb.line(int(cx + r0 * ca), int(cy + r0 * sa),
                          int(cx + r1 * ca), int(cy + r1 * sa), col)

    # ── text ─────────────────────────────────────────────────────────────
    def text(self, s, x, y, px, c):
        """Draw text with its top-left corner at (x, y)."""
        font = _load_font(px)
        col = _c565(c)
        fb = self._fb
        pen = int(x)
        top = int(y)
        height = font.height
        bitmap = font.bitmap
        for ch in s:
            width, offset = font.glyph(ord(ch))
            rowbytes = (width + 7) >> 3
            for row in range(height):
                base = offset + row * rowbytes
                yy = top + row
                if yy < 0 or yy >= self.h:
                    continue
                for bx in range(rowbytes):
                    byte = bitmap[base + bx]
                    if not byte:
                        continue
                    x0 = pen + (bx << 3)
                    for bit in range(8):
                        if byte & (0x80 >> bit):
                            fb.pixel(x0 + bit, yy, col)
            pen += width
        return pen - int(x)

    def measure(self, s, px):
        """(width, ascent, descent) of `s` at `px` pixels."""
        font = _load_font(px)
        width = 0
        for ch in s:
            width += font.glyph(ord(ch))[0]
        return width, font.ascent, font.height - font.ascent

    # ── regions / blits ──────────────────────────────────────────────────
    def scroll_up(self, dy):
        self._fb.scroll(0, -int(dy))
        self._fb.rect(0, self.h - int(dy), self.w, int(dy), 0, True)

    def snapshot(self, box):
        """Copy of the region (x0, y0, x1, y1); opaque to callers."""
        x0, y0, x1, y1 = box
        w = x1 - x0
        rows = []
        mv = memoryview(self._buf)
        for yy in range(y0, y1):
            start = (yy * self.w + x0) * 2
            rows.append(bytes(mv[start:start + w * 2]))
        return (w, y1 - y0, rows)

    def restore(self, snap, x, y):
        w, h, rows = snap
        mv = memoryview(self._buf)
        for i in range(h):
            start = ((y + i) * self.w + x) * 2
            mv[start:start + w * 2] = rows[i]

    def blit(self, src, x, y):
        """Blit another FbRaster (canvas push)."""
        self._fb.blit(src._fb, int(x), int(y))

    # ── images / QR ──────────────────────────────────────────────────────
    def paste_pil(self, img, x, y):
        raise NotImplementedError("PIL images: cpython runtime only")

    @staticmethod
    def _read_image(source):
        if isinstance(source, (bytes, bytearray, memoryview)):
            return bytes(source)
        with open(source, "rb") as fh:
            return fh.read()

    def draw_image(self, source, x, y, scale_x=1.0, scale_y=1.0):
        from stackchan_sim import pnglite
        try:
            w, h, rgba = pnglite.decode(self._read_image(source))
        except (ValueError, OSError):
            return False
        self.blit_rgba(w, h, rgba, x, y, scale_x, scale_y)
        return True

    def blit_rgba(self, w, h, rgba, x, y, scale_x=1.0, scale_y=1.0):
        """Straight-RGBA blit, 1-bit alpha (>=128), nearest scaling."""
        fb = self._fb
        dw = max(1, int(w * scale_x))
        dh = max(1, int(h * scale_y))
        scaled = not (dw == w and dh == h)
        for dy in range(dh):
            yy = y + dy
            if yy < 0 or yy >= self.h:
                continue
            sy = (dy * h // dh) if scaled else dy
            base = sy * w * 4
            for dx in range(dw):
                sx = (dx * w // dw) if scaled else dx
                s = base + sx * 4
                if rgba[s + 3] < 128:
                    continue
                fb.pixel(x + dx, yy,
                         ((rgba[s] & 0xF8) << 8) |
                         ((rgba[s + 1] & 0xFC) << 3) | (rgba[s + 2] >> 3))

    def image_size(self, source):
        from stackchan_sim import pnglite
        try:
            return pnglite.size(self._read_image(source))
        except (ValueError, OSError):
            return None

    def draw_qr(self, text, x, y, size):
        return False

    # ── output ───────────────────────────────────────────────────────────
    _can_compress = None

    def encode_frame(self):
        if FbRaster._can_compress is None:
            try:
                import deflate
                import io
                stream = deflate.DeflateIO(io.BytesIO(), deflate.ZLIB)
                stream.write(b"")  # needs MICROPY_PY_DEFLATE_COMPRESS
                FbRaster._can_compress = True
            except (ImportError, AttributeError):
                FbRaster._can_compress = False
        if not FbRaster._can_compress:
            return "rgb565", bytes(self._buf)
        import deflate
        import io
        out = io.BytesIO()
        stream = deflate.DeflateIO(out, deflate.ZLIB)
        stream.write(self._buf)
        stream.close()
        return "rgb565z", out.getvalue()
